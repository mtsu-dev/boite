import { afterAll, beforeAll, expect, test } from 'bun:test';
import { join } from 'node:path';
import { findChromium } from '../../packages/core/src/browser/chromium.ts';
import { makeAgent, scripted } from '../../packages/core/test/agent-fixture.ts';
import { startTestCore, type TestCore } from '../../packages/core/test/harness.ts';
import { BrowserPage } from './lib/cdp.ts';
import { ensureProductionUi } from './lib/prod-ui.ts';
import { mobileAction } from './lib/mobile.ts';

const real = findChromium().path ? test : test.skip;
const ARTIFACTS = join(import.meta.dir, '.artifacts', 'bot-project-workers');
let harness: TestCore;
let page: BrowserPage;
let restore: (() => void) | undefined;

beforeAll(() => ensureProductionUi(), 120_000);
afterAll(async () => { await page?.close(); await harness?.stop(); restore?.(); }, 30_000);

real('a bot project worker appears live in the project and opens as a conversation on desktop and phone', async () => {
  harness = await startTestCore();
  const owner = await harness.connect();
  const project = await owner.call('projects.add', { path: harness.dataDir, name: 'Worker project' });
  const bot = await makeAgent(harness, owner, { name: 'Scout', projectIds: [project.id] });
  restore = scripted(() => ({ text: 'Checking the project build. I will send the result to Scout.', hold: true })).restore;
  await owner.call('delegation.configure', { threadId: bot.threadId, config: { enabled: true, paused: false, profiles: [], anyModel: true } });
  page = await BrowserPage.launch({ url: `${harness.url}/?token=${harness.token}`, experiments: ['resident-agents'], windowSize: { width: 1440, height: 900 } });
  await page.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await page.waitFor(`document.querySelector('[data-testid=status-connection]')?.dataset.state === 'ready'`, 30_000);
  const worker = await owner.call('delegation.spawn', { threadId: bot.threadId, title: 'Verify project build', task: 'Verify the project build and report the result.', requestId: 'visible-worker' });
  expect(worker.thread).toMatchObject({ projectId: project.id, cwd: project.path, parentThreadId: bot.threadId });
  const row = `[data-testid="thread-row"][data-thread-id="${worker.thread.id}"]`;
  await page.waitFor(`document.querySelector(${JSON.stringify(row)})?.dataset.status === 'running'`);
  await page.click(row);
  await page.waitFor(`document.querySelector('[data-testid="composer-input"]') && document.body.textContent.includes('Verify the project build and report the result.')`);
  expect(await page.evaluate(`document.querySelector(${JSON.stringify(row)})?.textContent`)).toContain('Verify project build');
  await page.settleAnimations();
  await page.screenshot(join(ARTIFACTS, 'desktop.png'));
  await page.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await page.click('[data-testid="sidebar-toggle"]');
  await page.waitFor(`document.querySelector(${JSON.stringify(row)})?.getBoundingClientRect().width > 0`);
  await page.settleAnimations();
  await page.screenshot(join(ARTIFACTS, 'phone.png'));
  await page.click(row);
  await page.waitFor(`document.querySelector('[data-testid="composer-input"]')?.getBoundingClientRect().width > 0`);
  expect(await page.evaluate(`document.querySelector('.agents-main') === null`)).toBe(true);
  await owner.call('threads.archive', { threadId: bot.threadId });
  await owner.call('threads.archive', { threadId: worker.thread.id, archived: false });
  await page.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
  await page.send('Page.reload', {});
  await page.waitFor(`document.querySelector('[data-testid=status-connection]')?.dataset.state === 'ready'`, 30_000);
  await page.waitFor(`document.querySelector(${JSON.stringify(row)})?.getBoundingClientRect().width > 0`);
  expect((await owner.call('threads.list', {})).find(thread => thread.id === worker.thread.id)?.parentIsBot).toBe(true);
  await owner.call('threads.archive', { threadId: worker.thread.id });
  // Archived threads are a filter of the thread list; Settings' card leads there.
  await page.click('[data-testid="nav-settings"]');
  await page.click('[data-testid="settings-tab-general"]');
  await page.click('[data-testid="archived-show-list"]');
  const archivedWorker = `[data-testid="done-thread"][data-thread-id="${worker.thread.id}"]`;
  await page.waitFor(`document.querySelector(${JSON.stringify(archivedWorker)})`);
  await owner.call('threads.update', { threadId: worker.thread.id, title: 'Verified project build' });
  await page.waitFor(`document.querySelector(${JSON.stringify(archivedWorker)})?.textContent.includes('Verified project build')`);
  await page.evaluate(`document.querySelector(${JSON.stringify(archivedWorker)}).scrollIntoView({ block: 'center' })`);
  await page.waitFor(`(() => { const box = document.querySelector(${JSON.stringify(archivedWorker)}).getBoundingClientRect(); return box.top >= 0 && box.bottom <= innerHeight; })()`);
  await page.settleAnimations();
  await page.screenshot(join(ARTIFACTS, 'archive-desktop.png'));
  await page.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await mobileAction(page, 'mobile-settings');
  await page.click('[data-testid="mobile-settings-archived"]');
  await page.waitFor(`document.querySelector('[data-testid="mobile-lifecycle-archived"]')?.getAttribute('aria-pressed') === 'true' && document.querySelector(${JSON.stringify(archivedWorker)})`);
  await page.settleAnimations();
  await page.screenshot(join(ARTIFACTS, 'archive-phone.png'));
  expect(page.errors()).toEqual([]);
}, 90_000);
